import {build} from 'vite';
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const result=await build({configFile:false,root,publicDir:false,logLevel:'warn',build:{write:false,minify:true,target:'es2022',
  lib:{entry:resolve(root,'app/e2ee/legacy-worker.ts'),name:'GenesisLegacyTransportWorker',formats:['iife'],fileName:'e2ee-legacy-transport-worker'},
  rolldownOptions:{output:{codeSplitting:false}}}});
const output=Array.isArray(result)?result.flatMap(row=>row.output):result.output;
const entry=output.find(row=>row.type==='chunk'&&row.isEntry);
if(!entry||output.some(row=>row!==entry))throw new Error('Legacy worker must be a single self-contained classic script');
const generated='// Generated by scripts/export-e2ee-legacy-worker.mjs; edit app/e2ee/legacy-worker.ts.\n'+entry.code.trimEnd()+'\n';
const target=resolve(root,'public/e2ee-legacy-transport-worker.js');
if(process.argv.includes('--check')) {
  if(!existsSync(target)||readFileSync(target,'utf8').replaceAll('\r\n','\n')!==generated)throw new Error('E2EE_WORKER_BUNDLE_OUTDATED');
  console.log('E2EE legacy worker bundle matches its source and shared policy.');
}else {writeFileSync(target,generated);console.log(`E2EE legacy worker generated: ${Buffer.byteLength(generated)} bytes.`);}
