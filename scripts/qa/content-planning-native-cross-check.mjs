import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {validateStreamedPlanningOwnership} from '../../app/e2ee/migration-ownership.ts';
import {canonicalE2eeValue,verifyE2eeCommand} from '../../app/e2ee/commands.ts';
import {parseE2eeContentPlanJson} from '../../app/e2ee/file-manifest-json.ts';
import {decodeE2eeBytes,validateE2eeContext} from '../../app/e2ee/envelope.ts';
const [input,output]=process.argv.slice(2);if(!input||!output)throw new Error('Usage: content-planning-native-cross-check.mjs INPUT OUTPUT');
const vector=JSON.parse(readFileSync(input,'utf8'));assert.equal(vector.synthetic,true);assert.equal(vector.metadataOnly,true);
const checked=validateStreamedPlanningOwnership(vector.ownership,vector.expected);assert.equal(checked.protocol,3);
const hash=bytes=>createHash('sha256').update(bytes).digest('base64url'),canonical=canonicalE2eeValue(checked);
try{assert.equal(hash(canonical),vector.ownershipCanonicalHash);}finally{canonical.fill(0);}
const signer=await crypto.subtle.importKey('spki',decodeE2eeBytes(checked.signer,91),{name:'ECDSA',namedCurve:'P-256'},false,['verify']);
for(const original of checked.originals)await verifyE2eeCommand(original.packet,signer);
// Independently reconstruct the exact synthetic entity bytes generated by the
// device fixture, rather than comparing two hashes supplied by that device.
const raw=Buffer.from('\ufeff {\r\n"checkpointHash":'+JSON.stringify(vector.expected.checkpointHash)+',"directoryRevision":'+vector.expected.directoryRevision+
 ',"rows":[],"private":"SYNTHETIC ORIGINAL α😀'+'a'.repeat(17)+'"}\r\n','utf8');
assert.equal(checked.originals.length,1);
for(const original of checked.originals){assert.equal(original.completion.rawHash,hash(raw));assert.equal(original.completion.size,raw.length);}
const bytes=decodeE2eeBytes(vector.manifestBytes,1,4*1024*1024);
try{
 const manifest=parseE2eeContentPlanJson(bytes),plan=checked.plans.find(row=>row.attemptId===manifest.attemptId);assert.ok(plan?.completion);
 assert.equal(hash(bytes),plan.completion.manifestHash);assert.equal(manifest.migrationId,vector.expected.migrationId);assert.equal(manifest.sourceHash,vector.expected.sourceHash);
 assert.deepEqual(manifest.actor,vector.expected.actor);assert.deepEqual(manifest.target,vector.expected.target);assert.deepEqual(validateE2eeContext(manifest.context),{...plan.context});
 assert.equal(manifest.logical.length,plan.originals.length);
 for(const[index,row]of manifest.logical.entries()){assert.equal(row.plaintextHash,plan.originals[index].rawHash);assert.equal(row.size,plan.originals[index].size);}
 for(const field of ['fence','generation']){
  const bad=structuredClone(checked);bad.plans[0][field]=field==='fence'?vector.expected.lease.fence+1:vector.expected.lease.generation+1;
  assert.throws(()=>validateStreamedPlanningOwnership(bad,vector.expected));
 }
 const bad=structuredClone(checked);bad.plans[0].originals[0].rawHash=hash(Buffer.from('SYNTHETIC SUBSTITUTE'));assert.throws(()=>validateStreamedPlanningOwnership(bad,vector.expected));
 writeFileSync(output,JSON.stringify({status:'PASS_METADATA_INTEROP',kind:vector.expected.target.kind,signatures:checked.originals.length,plans:checked.plans.length,
  manifestBytes:bytes.length,manifestHash:hash(bytes),independentRawBytes:raw.length,independentRawHash:hash(raw),warning:'Synthetic native metadata and raw-byte digest binding only; not content recovery, OAuth, production or independent crypto review.'},null,2)+'\n');
}finally{bytes.fill(0);}
