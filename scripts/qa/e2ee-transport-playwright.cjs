// Playwright CLI --filename evaluates the function expression in its isolated runner.
// eslint-disable-next-line @typescript-eslint/no-unused-expressions
async (page) => {
  const checks=[];
  const check=(name,passed)=>{checks.push({name,passed});if(!passed)throw new Error(name);};
  const url=page.url();
  await page.waitForFunction(()=>globalThis.genesisTransportFixture?.state().ready);
  const second=await page.context().newPage();await second.goto(url);
  await second.waitForFunction(()=>globalThis.genesisTransportFixture?.state().ready);
  const owner='browser-transport-'+Date.now();
  await page.evaluate(owner=>globalThis.genesisTransportFixture.hold(owner),owner);
  await page.waitForFunction(owner=>globalThis.genesisTransportFixture.state()[`${owner}:entered`]===true,owner);
  const parallel=await page.context().newPage();await parallel.goto(url);
  await parallel.waitForFunction(()=>globalThis.genesisTransportFixture?.state().ready);
  await parallel.evaluate(owner=>globalThis.genesisTransportFixture.hold(owner),owner);
  await parallel.waitForFunction(owner=>globalThis.genesisTransportFixture.state()[`${owner}:entered`]===true,owner);
  check('ordinary private requests can run in parallel under shared permits',true);
  await second.evaluate(owner=>{
    globalThis.freezeResult=globalThis.genesisTransportFixture.freeze(owner);
  },owner);
  const locks=await second.evaluate(()=>navigator.locks.query());
  check('all tabs use the same real Web Lock',locks.held.length===2&&locks.held.every(lock=>lock.mode==='shared')&&locks.pending.length===1);
  check('migration has not committed ahead of old IO',await second.evaluate(owner=>globalThis.genesisTransportFixture.marker(owner),owner)===null);
  await page.evaluate(owner=>globalThis.genesisTransportFixture.release(owner),owner);
  await page.evaluate(owner=>globalThis.genesisTransportFixture.wait(owner),owner);
  check('migration still waits for the second complete response',await second.evaluate(owner=>globalThis.genesisTransportFixture.marker(owner),owner)===null);
  await parallel.evaluate(owner=>globalThis.genesisTransportFixture.release(owner),owner);
  await parallel.evaluate(owner=>globalThis.genesisTransportFixture.wait(owner),owner);await parallel.close();
  const token=await second.evaluate(()=>globalThis.freezeResult);
  check('complete old response precedes durable migration marker',typeof token==='string'&&await page.evaluate(owner=>globalThis.genesisTransportFixture.state()[`${owner}:parsed`]===true,owner));
  const before=await second.evaluate(()=>globalThis.genesisTransportFixture.count());
  const denied=await second.evaluate(owner=>globalThis.genesisTransportFixture.request(owner),owner);
  check('fenced request creates zero network probes',denied.error==='E2EE_LOCAL_LEGACY_TRANSPORT_FORBIDDEN'&&await second.evaluate(()=>globalThis.genesisTransportFixture.count())===before);
  const unrelated=await second.evaluate(()=>globalThis.genesisTransportFixture.request('unrelated-browser-owner'));
  check('independent owner remains available',unrelated.ok===true);
  await second.evaluate(()=>globalThis.genesisTransportFixture.reopen());
  check('connection reopening preserves the exact marker',(await second.evaluate(owner=>globalThis.genesisTransportFixture.marker(owner),owner)).token===token);
  await second.evaluate(owner=>globalThis.genesisTransportFixture.active(owner),owner);
  const rollback=await second.evaluate(owner=>globalThis.genesisTransportFixture.remove(owner),owner);
  check('real IndexedDB refuses active deletion',rollback.error==='E2EE_LOCAL_DOWNGRADE_FORBIDDEN');
  await second.close();const reopened=await page.context().newPage();await reopened.goto(url);
  await reopened.waitForFunction(()=>globalThis.genesisTransportFixture?.state().ready);
  const afterClose=await reopened.evaluate(owner=>globalThis.genesisTransportFixture.marker(owner),owner);
  check('new tab keeps active marker and exact token',afterClose.phase==='active'&&afterClose.token===token);
  const interrupted=owner+'-interrupted';
  await reopened.evaluate(owner=>globalThis.genesisTransportFixture.freezeHeld(owner),interrupted);
  await reopened.waitForFunction(owner=>globalThis.genesisTransportFixture.state()[`${owner}:snapshot`]===true,interrupted);
  await reopened.close();
  const afterDeath=await page.evaluate(owner=>globalThis.genesisTransportFixture.request(owner),interrupted);
  check('closing migration tab releases its lock and retains preparing denial',afterDeath.error==='E2EE_LOCAL_LEGACY_TRANSPORT_FORBIDDEN');
  const state=await page.evaluate(owner=>globalThis.genesisTransportFixture.marker(owner),interrupted);
  check('interrupted migration source is not replaced with an empty generation',state.phase==='preparing');
  const corruptOwner=owner+'-corrupt';await page.evaluate(owner=>globalThis.genesisTransportFixture.corruptMarker(owner),corruptOwner);
  const corruptBefore=await page.evaluate(()=>globalThis.genesisTransportFixture.count());
  const corrupt=await page.evaluate(owner=>globalThis.genesisTransportFixture.request(owner),corruptOwner);
  check('a stored null marker is corruption and cannot permit a request',corrupt.error==='E2EE_CORRUPT_LOCAL_FENCE'&&await page.evaluate(()=>globalThis.genesisTransportFixture.count())===corruptBefore);
  const corruptFreeze=await page.evaluate(async owner=>{try{await globalThis.genesisTransportFixture.freeze(owner);return 'unexpected';}catch(error){return error.message;}},corruptOwner);
  check('migration cannot replace a corrupt marker with an empty scope',corruptFreeze==='E2EE_CORRUPT_LOCAL_FENCE');
  const productOwner=await page.evaluate(()=>globalThis.genesisTransportFixture.productSession());
  check('application web API binds a live session owner',typeof productOwner==='string');
  const initial=await page.evaluate(()=>globalThis.genesisTransportFixture.productRequest());
  check('ordinary application API reaches only its bound synthetic owner',initial.ok===true);
  await page.evaluate(owner=>globalThis.genesisTransportFixture.freeze(owner),productOwner);
  const privateBefore=await page.evaluate(()=>globalThis.genesisTransportFixture.count());
  const productDenied=await page.evaluate(()=>globalThis.genesisTransportFixture.productRequest());
  check('application API cannot create a private request behind the marker',productDenied.error==='E2EE_LOCAL_LEGACY_TRANSPORT_FORBIDDEN'&&await page.evaluate(()=>globalThis.genesisTransportFixture.count())===privateBefore);
  const privatePreferences=await page.evaluate(()=>globalThis.genesisTransportFixture.productPreferences(true));
  check('application API protects private preference payloads',privatePreferences.error==='E2EE_LOCAL_LEGACY_TRANSPORT_FORBIDDEN');
  const metadataPreferences=await page.evaluate(()=>globalThis.genesisTransportFixture.productPreferences(false));
  check('technical preferences remain available',metadataPreferences.ok===true);
  const status=await page.evaluate(()=>globalThis.genesisTransportFixture.productStatus());
  check('signed transport discovery remains available',status.cryptoProtocol===1);
  const activeProfileOwner=await page.evaluate(()=>globalThis.genesisTransportFixture.activeProfile());
  check('clean client has no marker for an already active server account',await page.evaluate(owner=>globalThis.genesisTransportFixture.marker(owner),activeProfileOwner)===null);
  const activeBefore=await page.evaluate(()=>globalThis.genesisTransportFixture.count());
  const activeRequest=await page.evaluate(()=>globalThis.genesisTransportFixture.productRequest());
  check('active profile denies legacy IO even without a local marker',activeRequest.error==='E2EE_UPGRADE_REQUIRED'&&await page.evaluate(()=>globalThis.genesisTransportFixture.count())===activeBefore);
  return {status:'PASS',synthetic:true,checks};
}
